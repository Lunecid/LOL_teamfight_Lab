def generate(outroot: Path):
    gen_e1()
    gen_e2()
    gen_e3()
    gen_e4()
    gen_e5()
    gen_g0()
    latex = outroot / "thesis" / "latex"
    (latex / "config").mkdir(parents=True, exist_ok=True)
    (latex / "tables" / "gen").mkdir(parents=True, exist_ok=True)
    (outroot / "thesis" / "docs").mkdir(parents=True, exist_ok=True)
    written = {}
    written[latex / "config" / "numbers_supp.tex"] = R.tex()
    for fn, body in TABLES.items():
        written[latex / "tables" / "gen" / fn] = body
    written[outroot / "thesis" / "docs" / "NUMBERS_SUPP.md"] = R.md(TABLE_DESC)
    for p, s in written.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(s, encoding="utf-8")
    return written


