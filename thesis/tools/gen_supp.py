# ---------------------------------------------------------------- formatting
def sgn5(x):
    return f"{x:+.5f}"


def f5(x):
    return f"{x:.5f}"


def f4(x):
    return f"{x:.4f}"


def f3(x):
    return f"{x:.3f}"


def f1(x):
    return f"{x:.1f}"


def f8(x):
    return f"{x:.8f}"


def pct1(x):
    return f"{100 * x:.1f}"


def fint(n):
    return f"{int(n):,}".replace(",", "{,}")


def ci5(pair):
    lo, hi = pair
    return f"[{lo:+.5f}, {hi:+.5f}]"


def tex(s):
    return str(s).replace("_", r"\_").replace("%", r"\%")


# ---------------------------------------------------------------- registry
class Registry:
    def __init__(self):
        self.rows = []  # (macro, value, stat, num, den, cond, weight, source)
        self.names = set()

    def add(self, macro, value, stat, num="—", den="—", cond="—", weight="—", source="—"):
        if macro in self.names:
            raise SystemExit(f"duplicate macro {macro}")
        self.names.add(macro)
        self.rows.append((macro, value, stat, num, den, cond, weight, source))

    def tex(self):
        out = [
            "%% GENERATED by thesis/tools/gen_supp.py from docs/SUPPLEMENTARY_*_20260921.json and",
            "%% docs/G0_INTEGRITY_STATUS_20260921.json. Do not edit by hand; run the generator.",
            "%% Registry with statistic / numerator / denominator / source: thesis/docs/NUMBERS_SUPP.md",
            "",
        ]
        for m, v, *_ in self.rows:
            out.append(f"\\newcommand{{\\{m}}}{{{v}}}")
        return "\n".join(out) + "\n"

    def md(self, tables):
        out = [
            "# 보완 실험 수치 레지스트리 (NUMBERS_SUPP)",
            "",
            "`latex/config/numbers_supp.tex`와 `latex/tables/gen/*.tex`는 `tools/gen_supp.py`가 아래 출처에서 **생성**한다.",
            "손으로 고치지 않는다. `tools/check_numbers_supp.py`가 재생성해 차이가 있으면 실패한다.",
            "모든 값은 보완 실험(15.16 노출 이후의 진단, `docs/SUPPLEMENTARY_EXPERIMENT_DESIGN_20260921.md`)이며 헤드라인을 대체하지 않는다.",
            "반올림: Brier 4자리, ΔBrier·구간 5자리(부호 포함), 비율 3자리, 초 1자리.",
            "",
            "## 생성 표",
            "",
            "| 파일 | 내용 | 출처 |",
            "|---|---|---|",
        ]
        for fn, desc, src in tables:
            out.append(f"| `latex/tables/gen/{fn}` | {desc} | {src} |")
        out += [
            "",
            "## 매크로",
            "",
            "| 매크로 | 값 | 통계량 | 분자 | 분모 | 조건 | 가중 | 출처 파일 → 필드 |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for m, v, stat, num, den, cond, wt, src in self.rows:
            out.append(f"| `\\{m}` | {v} | {stat} | {num} | {den} | {cond} | {wt} | {src} |")
        return "\n".join(out) + "\n"


R = Registry()
TABLES = {}  # filename -> tex
TABLE_DESC = []

MW = "경기 가중 (1/n_m)"


def table(fn, desc, src, body):
    TABLES[fn] = body
    TABLE_DESC.append((fn, desc, src))


def wrap_table(caption, label, colspec, header, rows, note, size=r"\small", extra_pre=""):
    lines = [
        "%% GENERATED by thesis/tools/gen_supp.py -- do not edit",
        r"\begin{table}[!t]",
        r"  \centering",
        f"  \\caption{{{caption}}}",
        f"  \\label{{{label}}}",
        f"  {size}",
        extra_pre,
        f"  \\begin{{tabular}}{{{colspec}}}",
        r"    \toprule",
        "    " + header + r" \\",
        r"    \midrule",
    ]
    lines += ["    " + r + r" \\" for r in rows]
    lines += [r"    \bottomrule", r"  \end{tabular}", f"  \\tabnote{{{note}}}", r"\end{table}", ""]
    return "\n".join(l for l in lines if l is not None)


